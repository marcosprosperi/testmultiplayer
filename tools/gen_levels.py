# Builds the five race levels with levelgen2. Usage: gen_levels.py <scenes dir> [level numbers]
import sys
from levelgen2 import LevelBuilder

OUT = sys.argv[1]
WHICH = [int(a) for a in sys.argv[2:]] or [1, 2, 3, 4, 5]


def level1():
    """Pradera (easy): runs, small gaps, stairs, slimes, climbs and drops"""
    b = LevelBuilder("Level_1", "day", "grass", uid="uid://bxwdv7rjp1mf5", seed=11)
    b.run(20)
    b.spikes_run(groups=2, length=2)
    b.gap(5)
    b.enemies_run(["slime", "slime"], length=36)
    b.stairs(3, up=True)
    b.run(10, coins=True)
    b.gap(6)
    b.checkpoint()
    pop = b.uname("PopSpikes")
    b.button([pop])
    b.run(20, coins=True)
    b.stairs(3, up=False)
    b.retractable_run(auto=False, name=pop)
    b.gap(12, "falling")
    b.enemies_run(["slime", "spiky", "slime"], length=44)
    b.climb(levels=3)
    b.run(12, coins=True)
    b.gap(6)
    b.checkpoint()
    b.saw_run(26)
    b.drop(rows=10)
    b.enemies_run(["slime", "bat"], length=36)
    b.cannon_run()
    b.gap(7)
    door = b.uname("TrapDoor")
    b.button([door])
    b.run(24)
    b.checkpoint()
    b.spikes_run(groups=3, length=3)
    b.gap(8, "trapdoor", name=door)
    b.stairs(2, up=True)
    b.enemies_run(["spiky", "slime", "slime"], length=44)
    b.gap(12, "falling")
    b.climb(levels=2)
    b.run(16, coins=True)
    b.checkpoint()
    b.gap(6)
    b.enemies_run(["slime", "slime", "bat"], length=40)
    b.stairs(3, up=False)
    b.spikes_run(groups=2, length=2)
    b.gap(12, "mover")
    b.retractable_run(auto=True)
    b.drop(rows=8)
    b.saw_run(24)
    b.climb(levels=2)
    b.enemies_run(["spiky", "slime"], length=36)
    b.fan_run(auto=True)
    b.finish()
    return b


